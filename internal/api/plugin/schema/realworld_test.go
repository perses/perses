// repoRoot returns the repository root by walking up 4 levels from this file's directory.
// This file lives at internal/api/plugin/schema/realworld_test.go.
func repoRoot(t *testing.T) string {
	t.Helper()
	_, filename, _, _ := runtime.Caller(0)
	abs, err := filepath.Abs(filepath.Join(filepath.Dir(filename), "..", "..", "..", ".."))
	require.NoError(t, err)
	return abs
}

// loadPluginDir loads all schemas from a plugin directory (e.g. plugins/Table-0.14.0-beta.7)
// using the plugins declared in package.json's perses.plugins array.
// All plugins in a module are passed in a single ModuleSpec so Load() can match schema kinds.
func loadPluginDir(t *testing.T, sch Schema, pluginDir string) {
	t.Helper()

	pkgJSON, err := os.ReadFile(filepath.Join(pluginDir, "package.json"))
	require.NoError(t, err, "reading package.json from %s", pluginDir)

	var pkg struct {
		Perses struct {
			SchemasPath string `json:"schemasPath"`
			Plugins     []struct {
				Kind string `json:"kind"`
				Spec struct {
					Name string `json:"name"`
				} `json:"spec"`
			} `json:"plugins"`
		} `json:"perses"`
	}
	require.NoError(t, json.Unmarshal(pkgJSON, &pkg))

	schemasPath := pkg.Perses.SchemasPath
	if schemasPath == "" {
		schemasPath = "schemas"
	}

	var modulePlugins []specModule.Plugin
	for _, p := range pkg.Perses.Plugins {
		kind := specPlugin.Kind(p.Kind)
		switch kind {
		case specPlugin.KindPanel, specPlugin.KindVariable, specPlugin.KindQuery,
			specPlugin.KindDatasource, specPlugin.KindAnnotation:
		default:
			continue
		}
		modulePlugins = append(modulePlugins, specModule.Plugin{
			Kind: kind,
			Spec: specModule.PluginSpec{Name: p.Spec.Name},
		})
	}

	if len(modulePlugins) == 0 {
		return
	}

	moduleSpec := v1.ModuleSpec{
		SchemasPath: schemasPath,
		Plugins:     modulePlugins,
	}
	if loadErr := sch.Load(pluginDir, v1.PluginModule{Spec: moduleSpec}); loadErr != nil {
		t.Logf("WARN: could not load plugins from %s: %v", pluginDir, loadErr)
	} else {
		t.Logf("Loaded %d plugin(s) from %s", len(modulePlugins), pluginDir)
	}
}

// TestRealWorldCephDashboard validates the ceph_capacity_quick_view dashboard
// (Table panels + Prometheus queries/variables) against the schema generated by this PR branch,
// exactly as `cue vet -d '#Dashboard' schema.cue dashboard.json` does.
func TestRealWorldCephDashboard(t *testing.T) {
	root := repoRoot(t)
	pluginsDir := filepath.Join(root, "plugins")

	// The plugins used by the ceph dashboard
	pluginDirs := []string{
		filepath.Join(pluginsDir, "Table-0.14.0-beta.7"),
		filepath.Join(pluginsDir, "Prometheus-0.58.0"),
	}

	sch := New()
	for _, dir := range pluginDirs {
		loadPluginDir(t, sch, dir)
	}

	schemaValue, err := sch.GenerateDashboardSchema()
	require.NoError(t, err, "GenerateDashboardSchema failed")

	ctx := cuecontext.New()
	exported, err := apiCue.Marshal(schemaValue)
	require.NoError(t, err)

	schema := ctx.CompileBytes(exported)
	require.NoError(t, schema.Err(), "compiled schema has errors")

	dashboardDef := schema.LookupPath(cue.MakePath(cue.Def("#Dashboard")))
	require.NoError(t, dashboardDef.Err(), "#Dashboard definition missing from schema")

	dashboardBytes, err := os.ReadFile(filepath.Join(root, "dev", "manual-testing", "ceph_capacity_quick_view.json"))
	require.NoError(t, err, "reading dashboard fixture")

	dashboardVal := ctx.CompileBytes(dashboardBytes)
	require.NoError(t, dashboardVal.Err(), "dashboard JSON is not valid CUE/JSON")

	err = dashboardDef.Unify(dashboardVal).Validate(cue.Concrete(true))
	if err != nil {
		t.Errorf("dashboard failed schema validation:\n%v", err)
	}
}
