package get

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"time"

	persesCMD "github.com/perses/perses/internal/cli/cmd"
	"github.com/perses/perses/internal/cli/config"
	"github.com/perses/perses/pkg/client/api"
	v1 "github.com/perses/perses/pkg/client/api/v1"
	"github.com/sirupsen/logrus"
	"github.com/spf13/cobra"
)

const (
	dashboardsKind = "dashboards"
	pluginsKind    = "plugins"
)

// now is a variable so the tests can use a fixed time.
var now = time.Now

type option struct {
	persesCMD.Option
	writer     io.Writer
	errWriter  io.Writer
	kind       string
	pluginName string
	version    string
	registry   string
	outputFile string
	apiClient  api.ClientInterface
}

func (o *option) Complete(args []string) error {
	if len(args) == 0 {
		return fmt.Errorf("you have to specify the schema to get: %q or %q", dashboardsKind, pluginsKind)
	}
	o.kind = args[0]
	if len(args) > 1 {
		o.pluginName = args[1]
	}
	if len(args) > 2 {
		return fmt.Errorf("too many arguments")
	}
	apiClient, err := config.Global.GetAPIClient()
	if err != nil {
		return err
	}
	o.apiClient = apiClient
	return nil
}

func (o *option) Validate() error {
	switch o.kind {
	case dashboardsKind:
		if len(o.pluginName) > 0 {
			return fmt.Errorf("no additional argument is supported with %q", dashboardsKind)
		}
	case pluginsKind:
	default:
		return fmt.Errorf("unknown schema %q, supported values are %q and %q", o.kind, dashboardsKind, pluginsKind)
	}
	if (len(o.version) > 0 || len(o.registry) > 0) && len(o.pluginName) == 0 {
		return fmt.Errorf("--version and --registry can only be used when getting the schema of a single plugin")
	}
	return nil
}

func (o *option) Execute() error {
	data, err := o.getSchema()
	if err != nil {
		return err
	}
	var buf bytes.Buffer
	buf.WriteString(o.header())
	buf.Write(data)
	if len(o.outputFile) > 0 {
		if writeErr := os.WriteFile(o.outputFile, buf.Bytes(), 0600); writeErr != nil {
			return writeErr
		}
		_, err = fmt.Fprintf(o.writer, "schema written to %s\n", o.outputFile)
		return err
	}
	_, err = o.writer.Write(buf.Bytes())
	return err
}

func (o *option) getSchema() ([]byte, error) {
	schemaClient := o.apiClient.V1().Schema()
	if o.kind == dashboardsKind {
		return schemaClient.Dashboard()
	}
	if len(o.pluginName) > 0 {
		return schemaClient.Plugin(o.pluginName, &v1.PluginSchemaQuery{Version: o.version, Registry: o.registry})
	}
	return schemaClient.Plugins()
}

// header returns CUE comments describing where and when the schema has been downloaded.
// A schema is tied to the version of the server and the plugins it loads,
// so this helps to notice when a downloaded schema is outdated.
func (o *option) header() string {
	var buf bytes.Buffer
	buf.WriteString("// Generated by percli schema get.\n")
	if restClient := o.apiClient.RESTClient(); restClient != nil && restClient.BaseURL != nil && restClient.BaseURL.URL != nil {
		// Drop the credentials that can be part of the URL (user info, or a token in the query or the fragment),
		// so they don't end up in the schema file.
		source := *restClient.BaseURL.URL
		source.User = nil
		source.RawQuery = ""
		source.ForceQuery = false
		source.Fragment = ""
		source.RawFragment = ""
		_, _ = fmt.Fprintf(&buf, "// Source: %s\n", source.String())
	}
	if health, err := o.apiClient.V1().Health().Check(); err != nil {
		logrus.WithError(err).Debug("unable to get the server version")
	} else {
		_, _ = fmt.Fprintf(&buf, "// Perses version: %s (commit %s)\n", health.Version, health.Commit)
	}
	_, _ = fmt.Fprintf(&buf, "// Downloaded at: %s\n\n", now().UTC().Format(time.RFC3339))
	return buf.String()
}

func (o *option) SetWriter(writer io.Writer) {
	o.writer = writer
}

func (o *option) SetErrWriter(errWriter io.Writer) {
	o.errWriter = errWriter
}

func NewCMD() *cobra.Command {
	o := &option{}
	cmd := &cobra.Command{
		Use:   "get (dashboards | plugins [NAME])",
		Short: "Download a CUE schema from the Perses server",
		Long: `
Download a CUE schema from the Perses server you are logged in to.

- "dashboards" is the complete dashboard schema, including the schemas of all the plugins loaded by the server.
  It defines #Dashboard, which can be used to validate dashboards offline.
- "plugins" is the schema definitions of all the loaded plugins, or of a single plugin when NAME is set.

The schema matches the version of the server and the plugins it loads, so download it again when the server is upgraded.
The output starts with comments giving the server URL, its version and the download time.
`,
		Example: `
# Download the complete dashboard schema
percli schema get dashboards > dashboard-schema.cue

# Write it to a file
percli schema get dashboards --output-file dashboard-schema.cue

# Get the schema of all the plugins, or of a single one
percli schema get plugins
percli schema get plugins TimeSeriesChart --version 0.14.0
`,
		RunE: func(cmd *cobra.Command, args []string) error {
			return persesCMD.Run(o, cmd, args)
		},
	}
	cmd.Flags().StringVar(&o.outputFile, "output-file", "", "Write the schema to this file instead of the standard output.")
	cmd.Flags().StringVar(&o.version, "version", "", "Version of the plugin. Only used when getting the schema of a single plugin. Default to the latest version.")
	cmd.Flags().StringVar(&o.registry, "registry", "", "Registry of the plugin. Only used when getting the schema of a single plugin. Default to the default registry.")
	return cmd
}
