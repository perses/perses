const expectedHeader = `// Generated by percli schema get.
// Source: http://localhost:8080
// Perses version: v0.1.0 (commit ff30323938a15cfa9df3071bb84e3f3ef75153df)
// Downloaded at: 2026-10-23T12:00:00Z

`

func fixNow(t *testing.T) {
	t.Helper()
	previous := now
	now = func() time.Time { return time.Date(2026, 10, 23, 12, 0, 0, 0, time.UTC) }
	t.Cleanup(func() { now = previous })
}

func TestSchemaGetCMD(t *testing.T) {
	fixNow(t)
	testSuite := []cmdTest.Suite{
		{
			Title:           "no args",
			Args:            []string{},
			APIClient:       fakeapi.New(),
			IsErrorExpected: true,
			ExpectedMessage: `you have to specify the schema to get: "dashboards" or "plugins"`,
		},
		{
			Title:           "unknown schema",
			Args:            []string{"datasources"},
			APIClient:       fakeapi.New(),
			IsErrorExpected: true,
			ExpectedMessage: `unknown schema "datasources", supported values are "dashboards" and "plugins"`,
		},
		{
			Title:           "name not supported for dashboards",
			Args:            []string{"dashboards", "foo"},
			APIClient:       fakeapi.New(),
			IsErrorExpected: true,
			ExpectedMessage: `no additional argument is supported with "dashboards"`,
		},
		{
			Title:           "version without plugin name",
			Args:            []string{"plugins", "--version", "1.0.0"},
			APIClient:       fakeapi.New(),
			IsErrorExpected: true,
			ExpectedMessage: "--version and --registry can only be used when getting the schema of a single plugin",
		},
		{
			Title:           "not logged in",
			Args:            []string{"dashboards"},
			IsErrorExpected: true,
			ExpectedMessage: "you are not connected to any API",
		},
		{
			Title:           "get the dashboard schema",
			Args:            []string{"dashboards"},
			APIClient:       fakeapi.New(),
			ExpectedMessage: expectedHeader + fakev1.FakeDashboardSchema,
		},
		{
			Title:           "get the plugin schemas",
			Args:            []string{"plugins"},
			APIClient:       fakeapi.New(),
			ExpectedMessage: expectedHeader + fakev1.FakePluginsSchema,
		},
		{
			Title:           "get a single plugin schema",
			Args:            []string{"plugins", "TimeSeriesChart", "--version", "0.14.0"},
			APIClient:       fakeapi.New(),
			ExpectedMessage: expectedHeader + fakev1.FakePluginsSchema,
		},
	}
	cmdTest.ExecuteSuiteTest(t, NewCMD, testSuite)
}

func TestSchemaGetCMDOutputFile(t *testing.T) {
	fixNow(t)
	outputFile := filepath.Join(t.TempDir(), "dashboard-schema.cue")
	cmdTest.ExecuteSuiteTest(t, NewCMD, []cmdTest.Suite{
		{
			Title:           "write the dashboard schema to a file",
			Args:            []string{"dashboards", "--output-file", outputFile},
			APIClient:       fakeapi.New(),
			ExpectedMessage: "schema written to " + outputFile + "\n",
		},
	})
	data, err := os.ReadFile(outputFile) // nolint: gosec
	require.NoError(t, err)
	assert.Equal(t, expectedHeader+fakev1.FakeDashboardSchema, string(data))
}

func TestSchemaGetCMDSourceWithoutCredentials(t *testing.T) {
	fixNow(t)
	apiClient := fakeapi.New()
	apiClient.RESTClient().BaseURL = common.MustParseURL("https://user:secret@perses.example.com?access_token=secret#private")
	cmdTest.ExecuteSuiteTest(t, NewCMD, []cmdTest.Suite{
		{
			Title:     "credentials in the server URL (user info, query, fragment) are not written in the schema",
			Args:      []string{"dashboards"},
			APIClient: apiClient,
			ExpectedMessage: `// Generated by percli schema get.
// Source: https://perses.example.com
// Perses version: v0.1.0 (commit ff30323938a15cfa9df3071bb84e3f3ef75153df)
// Downloaded at: 2026-10-23T12:00:00Z

` + fakev1.FakeDashboardSchema,
		},
	})
}
